import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
await fs.mkdir('qa/feedback', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 402, height: 874 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const capture = async (name) => {
  await page.waitForFunction(() => document.fonts.check('15px Inter_400Regular'));
  await page.waitForFunction(() => [...document.querySelectorAll('img')].every(img => img.complete && img.naturalWidth > 0));
  await page.screenshot({ path: `qa/feedback/${name}.png` });
};
await page.goto('http://localhost:8081/trip');
await page.getByRole('textbox', { name: 'Mensagem para o assistente de viagem' }).waitFor();
await capture('trip-initial');
await page.getByRole('button', { name: 'De Brasília para São Paulo', exact: true }).click();
await page.getByTestId('trip-plan').waitFor();
await capture('trip-plan');
await page.getByRole('button', { name: 'Ver paradas da viagem' }).click();
await capture('trip-stops');
await page.goto('http://localhost:8081/charging');
await page.getByRole('button', { name: 'Voltar para o início', exact: true }).waitFor();
await capture('charging');
await page.getByText('Informações da sessão', { exact: true }).scrollIntoViewIfNeeded();
await capture('charging-details');
await page.setViewportSize({ width: 360, height: 740 });
await capture('charging-small');
await page.goto('http://localhost:8081/trip');
await page.getByRole('button', { name: 'Nova conversa' }).click();
await capture('trip-small');
await fs.writeFile('qa/feedback/browser-errors.json', JSON.stringify(errors, null, 2));
console.log('Captured 7 feedback screenshots. Browser errors:', errors);
await browser.close();
